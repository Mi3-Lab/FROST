"""Macros for the v7 update: Qwen-Drive v3 (registered, 400 held-out clips), Alpamayo-2 on the Heun-64 reference
(addendum 20), the fully compiled Alpamayo-1.5 on DRIVE AGX Thor (Thor addendum 3) and Qwen-Drive precision on Thor.
Every value is read from a stored artifact. Run: python reproduce/tables/make_crossmodel_numbers.py (writes numbers_crossmodel.tex; the paper calls it numbers_v7.tex)
"""
import json
from pathlib import Path

import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from repro_paths import RESULTS, TABLES as OUT  # noqa: E402
ART = RESULTS
load = lambda p: json.loads((ART / p).read_text())
ci = lambda x, d, s=1.: f'[{s * x[0]:.{d}f},\\,{s * x[1]:.{d}f}]'.replace('-', '$-$')


def main():
    out = ['% Generated by paper/tables/make_numbers_v7.py; do not edit by hand.']
    mac = lambda k, v: out.append(f'\\newcommand{{\\{k}}}{{{v}}}')

    q = load('qwendrive_v3_analysis_20261102/summary.json')
    h = q['horizons']['native_5s'];s10, s4 = h['samplers']['euler10_t1.0'], h['samplers']['euler4_t1.0'];c = h['curve']
    mac('QVClips', q['distinct_clip_ids'])
    mac('QVETenTau', f"{s10['tau_eff']:.2f}")
    mac('QVETenAdeResid', ci(s10['ade1']['residual_ci90'], 4))
    mac('QVETenFlipResid', ci(s10['flip']['residual_ci90'], 2, 100))
    mac('QVEFourTau', f"{s4['tau_eff']:.2f}")
    mac('QVEFourTauCI', ci(s4['tau_eff_ci95'], 2))
    mac('QVEFourAdeResidCm', f"{100 * s4['ade1']['residual']:.1f}")
    mac('QVEFourAdeResid', ci(s4['ade1']['residual_ci90'], 3))
    mac('QVEFourFlipResid', f"{100 * s4['flip']['residual']:.1f}")
    mac('QVEFourFlipResidCI', ci(s4['flip']['residual_ci90'], 1, 100))
    mac('QVEFourLongResidCI', ci(s4['flip_long']['residual_ci90'], 1, 100))
    mac('QVEFourLatResidCI', ci(s4['flip_lat']['residual_ci90'], 1, 100))
    mac('QVCoolGainMm', f"{1000 * (c['heun32_t1.0']['ade1'] - c['heun32_t0.3']['ade1']):.0f}")
    common = q['horizons']['common_4s']['samplers']['euler4_t1.0']['flip']
    mac('QVEFourFlipResidFourS', ci(common['residual_ci90'], 1, 100))
    assert s10['ade1']['equivalent'] and s10['flip']['equivalent'] and s4['ade1']['equivalent'] and not s4['flip']['equivalent']

    hq = load('qwendrive_v3_heun_analysis_20261102/summary.json')['horizons']['native_5s']['samplers']['heun5_t1.0']
    mac('QHSpreadPct', f"{100 * (hq['spread'] / c['heun32_t1.0']['spread'] - 1):.0f}")
    mac('QHFlipResid', f"{100 * hq['flip']['residual']:.1f}~{ci(hq['flip']['residual_ci90'], 1, 100)}")
    mac('QHFlipClips', hq['flip']['clips_with_flip_sampler'])
    assert hq['above_grid']
    q6 = load('qwendrive_v3_e6_analysis_20261102/summary.json');e6 = q6['horizons']['native_5s']['samplers']['euler6_t1.0']
    assert q6['R2']['pass'] and all(q6['predictions'].values())
    mac('QVESixTau', f"{e6['tau_eff']:.2f}")
    mac('QVESixFlipResid', f"{100 * e6['flip']['residual']:.1f}~{ci(e6['flip']['residual_ci90'], 1, 100)}")
    conv = load('convergence_ext_summary_qwen_20261101/summary.json')
    mac('QVConvPairs', len(conv))
    mac('QVConvMaxMm', f"{1000 * max(r['d256_512'] for r in conv):.2f}")
    mac('QVConvAgree', sum(r['agree256'] and r['agree128'] for r in conv))
    mac('QVConvClips', len({r['clip'] for r in conv}))

    import statistics as st
    for tag, name in (('SW', 'simwam_20261101'), ('CN', 'cosmos_c01234_20261102')):
        d = load(f'convergence_ext_summary_{name}/summary.json');v = [r['d256_512'] for r in d]
        mac(f'{tag}ConvClips', len({r['clip'] for r in d}));mac(f'{tag}ConvPlans', len(d))
        mac(f'{tag}ConvMed', f'{st.median(v):.1f}');mac(f'{tag}ConvMax', f'{max(v):.1f}')
        assert not any(r['adaptive'].get('rk45_1e-07', {}).get('ok') for r in d)

    a2 = load('convergence_a20_analysis_a2_v1_20261031/results.json')['matched']['heun64']['euler10_a20']
    mac('CVATauSixtyFour', f"{a2['tau_eff'][0]:.2f}")
    mac('CVAAdeResid', ci(a2['ade1']['tost90'], 3))
    mac('CVAFlipResid', ci(a2['flip']['tost90'], 1, 100))
    assert a2['ade1']['equivalent'] and a2['flip']['equivalent']

    t = load('thor_addendum3_analysis_v1_20261101/summary.json')
    taus = [t['variants_own_curve'][v]['euler10_t1.0']['tau_eff'][0] for v in ('V0', 'V1', 'V3', 'V4')]
    assert all(t['variants_own_curve'][v]['euler10_t1.0'][m]['equivalent'] for v in ('V3', 'V4') for m in ('ade1', 'flip'))
    mac('TCETenTauLo', f'{min(taus):.2f}');mac('TCETenTauHi', f'{max(taus):.2f}')
    mac('TCDtauMax', f"{max(abs(v['euler10_t1.0']['dtau_eff']) for v in t['shift'].values()):.3f}")
    f4 = t['variants_own_curve']['V3']['euler4_t1.0']['flip']
    mac('TCEFourFlipVThree', f"{100 * f4['residual'][0]:.1f}~{ci(f4['ci90'], 1, 100)}")
    assert not f4['equivalent']
    rz = t['reasoning']['V3'];v = t['verdicts']
    mac('TCTextSame', rz['text_identical']);mac('TCTextN', rz['clips_with_pytorch_text'])
    mac('TCPassed', sum(x.get('verdict') == 'PASS' for x in v.values()));mac('TCPreds', len(v))
    assert v['W4']['verdict'] == 'FAIL'
    b = load('thor_vlm_trt_20261031/out/bench_fp8_s1_gpupre.json')['median']
    mac('TCPlanEtenS', f"{b['total_e10_ms'] / 1000:.2f}")
    mac('TCPlanEfourS', f"{b['total_e4_ms'] / 1000:.2f}")
    mac('TCFieldEtenMs', f"{b['e10_ms']:.0f}")

    fid = lambda d: load(f'thor_qwendrive_20261101/{d}/fidelity.json')
    bf, fp = fid('trt40_bf16'), fid('trt40_fp32_gd')
    mac('QTClips', bf['n']);mac('QTEagerRatio', f"{fid('eager40')['spread_ratio']:.2f}")
    mac('QTBfRatio', f"{bf['spread_ratio']:.2f}");mac('QTBfRatioCI', ci(bf['spread_ci95'], 2))
    mac('QTFpRatio', f"{fp['spread_ratio']:.3f}");mac('QTFpRatioCI', ci(fp['spread_ci95'], 3))
    (OUT / 'numbers_crossmodel.tex').write_text('\n'.join(out) + '\n')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
