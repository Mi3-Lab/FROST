"""Robustness macros and table (EXPLORATORY / POST HOC, not pre-registered) from artifacts/robustness_v1_20261102/summary.json
(frost/analysis/robustness.py). Writes tables/numbers_robustness.tex (macros, prefix \\Rob) and tables/tab_robustness.tex.

Run from the repo root: python reproduce/tables/make_robustness.py
"""
import json
from pathlib import Path

import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from repro_paths import RESULTS, TABLES as OUT  # noqa: E402
SRC = RESULTS / 'robustness_v1_20261102/summary.json'
MODELS = [('alpamayo15', 'AOneFive', 'Alpamayo-1.5'), ('alpamayo_r1', 'ROne', 'Alpamayo-R1'), ('alpamayo2', 'ATwo', 'Alpamayo-2'), ('qwendrive', 'QD', 'Qwen-Drive')]
SAMPLERS = [('euler10_t1.0', 'ETen', '$E_{10}$'), ('euler4_t1.0', 'EFour', '$E_4$'), ('heun5_t1.0', 'HeunFive', 'Heun-5')]
STATS = [('spread', 'Mean'), ('spread_long', 'Long'), ('spread_lat', 'Lat'), ('spread_median', 'Median'), ('energy', 'Energy')]
THR = ['all_x0.8', 'all_x0.9', 'all_x1.1', 'all_x1.2', 'stop_x0.8', 'stop_x1.2', 'band_x0.8', 'band_x1.2', 'heading_x0.8', 'heading_x1.2', 'offset_x0.8', 'offset_x1.2']


def num(x, d=2):
    t = f'{x:.{d}f}'
    if float(t) == 0: t = f'{0:.{d}f}'
    return t.replace('-', '$-$')


def pct(x): return num(100 * x, 0)


def main():
    r = json.loads(SRC.read_text()); assert r['status'].startswith('EXPLORATORY'); assert r['boot'] == 2000
    L = ['% Generated by paper/tables/make_robustness.py from artifacts/robustness_v1_20261102 (EXPLORATORY / POST HOC); do not edit by hand.']
    add = lambda k, v: L.append(f'\\newcommand{{\\Rob{k}}}{{{v}}}')
    rows = []; changed = 0; cells = 0
    for key, tag, mlabel in MODELS:
        first = True
        for s, stag, slabel in SAMPLERS:
            if s not in r['q1_matching'].get(key, {}): continue
            q1 = r['q1_matching'][key][s]; base = q1['spread']
            for st, sname in STATS:
                e = q1[st]; add(f'{tag}{stag}Tau{sname}', num(e['tau_eff']))
                for m, mn in [('ade1', 'Ade'), ('flip', 'Flip')]:
                    add(f'{tag}{stag}{mn}Eq{sname}', 'yes' if e[m]['equivalent'] else 'no')
                    if st != 'spread': cells += 1; changed += e[m]['equivalent'] != base[m]['equivalent']
            q2 = r['q2_fraction'][key][s]
            for m, mn in [('ade1', 'Ade'), ('flip', 'Flip')]:
                f = q2[m]
                if f['fraction_reproduced'] is not None and f['fraction_reproduced_ci95'] is not None:
                    add(f'{tag}{stag}Share{mn}', pct(f['fraction_reproduced'])); add(f'{tag}{stag}Share{mn}Lo', pct(f['fraction_reproduced_ci95'][0]))
                    add(f'{tag}{stag}Share{mn}Hi', pct(f['fraction_reproduced_ci95'][1]))
                if f['margin_over_effect'] is not None: add(f'{tag}{stag}MarginOverEffect{mn}', pct(f['margin_over_effect']))
            q3 = r['q3_noises'][key][s]
            for k in (3, 4, 5):
                e = q3[f'k{k}']; add(f'{tag}{stag}TauMinK{"Three Four Five".split()[k - 3]}', num(e['tau_eff_min'])); add(f'{tag}{stag}TauMaxK{"Three Four Five".split()[k - 3]}', num(e['tau_eff_max']))
            tw = r['q3_two_way_bootstrap'][key].get(s)
            if tw:
                for m, mn in [('ade1', 'Ade'), ('flip', 'Flip')]:
                    sc = 1 if m == 'ade1' else 100; d = 3 if m == 'ade1' else 1
                    add(f'{tag}{stag}TwoWay{mn}Lo', num(sc * tw[m]['ci90'][0], d)); add(f'{tag}{stag}TwoWay{mn}Hi', num(sc * tw[m]['ci90'][1], d))
                    add(f'{tag}{stag}TwoWay{mn}Eq', 'yes' if tw[m]['equivalent'] else 'no')
            q4 = r['q4_thresholds'][key][s]; same = sum(q4[v]['flip']['equivalent'] == q4['original']['flip']['equivalent'] for v in THR)
            add(f'{tag}{stag}ThrSame', same)
            sh = lambda m: (f"{pct(q2[m]['fraction_reproduced'])}\\,{{\\scriptsize[{pct(q2[m]['fraction_reproduced_ci95'][0])},{pct(q2[m]['fraction_reproduced_ci95'][1])}]}}"
                            if q2[m]['fraction_reproduced_ci95'] is not None and (q2[m]['effect_ci95'][0] > 0 or q2[m]['effect_ci95'][1] < 0)
                            and q2[m]['fraction_reproduced_ci95'][1] - q2[m]['fraction_reproduced_ci95'][0] < 1.0 else '--')
            mark = lambda e: e['ade1']['equivalent'] and e['flip']['equivalent']
            taus = [num(q1[st]['tau_eff']) + ('' if mark(q1[st]) == mark(base) else '$^\\ast$') for st, _ in STATS]
            k3 = q3['k3']
            rows.append(' & '.join([mlabel if first else '', slabel, *taus, sh('ade1'), sh('flip'), f"{num(k3['tau_eff_min'])}--{num(k3['tau_eff_max'])}", f'{same}/{len(THR)}']) + ' \\\\')
            first = False
        rows.append('\\midrule')
    rows = rows[:-1]
    add('ThrVariants', len(THR)); add('MatchVerdictChanges', changed); add('MatchVerdictCells', cells)
    # planted recovery (Q6)
    pa = r['q6_planted']['a_reference_as_sampler']
    cs = [abs(v['tau_eff_mean'] - float(t)) for d in pa.values() for t, v in d['clip_split'].items()]
    add('PlantedClipSplitMaxBias', num(max(cs), 3))
    ns = [d['noise_split']['ref_spread_ratio_B_over_A'] for d in list(pa.values())[:3]]
    add('NoiseSetSpreadRatioMin', num(min(x['min'] for x in ns))); add('NoiseSetSpreadRatioMax', num(max(x['max'] for x in ns)))
    pb = r['q6_planted']['b_scaled_noise_euler10']
    for key, tag, _ in MODELS[:3]:
        for t in ['0.9', '0.8', '0.7', '0.6']:
            e = pb[key][t]; tt = {'0.9': 'Nine', '0.8': 'Eight', '0.7': 'Seven', '0.6': 'Six'}[t]
            add(f'{tag}Scaled{tt}Tau', num(e['tau_eff'])); add(f'{tag}Scaled{tt}Pred', num(e['predicted_tau_eff']))
            add(f'{tag}Scaled{tt}FlipResid', num(100 * e['flip']['residual'], 1)); add(f'{tag}Scaled{tt}FlipEq', 'yes' if e['flip']['equivalent'] else 'no')
    for key, tag, _ in MODELS:
        e = r['q7_e1'][key]; add(f'{tag}EOneSpread', pct(e['spread'])); add(f'{tag}EOneSpreadLong', pct(e['spread_long'])); add(f'{tag}EOneSpreadLat', pct(e['spread_lat']))
    for key, tag, _ in MODELS[:3]:
        q = r['q5_heun'][key]; c = q['convergence']
        add(f'{tag}HFiveToHThirtyTwo', num(c['heun5_vs_heun32_median_m'])); add(f'{tag}HThirtyTwoToHSixtyFour', num(c['heun32_vs_heun64_median_m'], 3))
        for s, stag in [('euler10_t1.0', 'ETen'), ('heun5_t1.0', 'HeunFive'), ('heun32_t0.8', 'RefEight')]:
            v = q['vs_reference'][s]; add(f'{tag}{stag}NoiseDist', num(v['per_noise_dist_median_m'])); add(f'{tag}{stag}FlipsNearBoundary', pct(v['flips_ref_margin_below_0.25']))
            add(f'{tag}{stag}FlipRateFar', num(100 * v['flip_rate_given_ref_margin_above_0.25'], 1)); add(f'{tag}{stag}LatFlip', num(100 * v['lat_flip_rate'], 1))
    # Ranges across the three Alpamayo models (main-text macros)
    A = [k for k, _, _ in MODELS[:3]]
    def rng(name, vals, fmt):
        add(f'{name}Min', fmt(min(vals))); add(f'{name}Max', fmt(max(vals)))
    E = 'euler10_t1.0'; H = 'heun5_t1.0'; q2 = r['q2_fraction']; q1 = r['q1_matching']; q5 = r['q5_heun']; q7 = r['q7_e1']
    rng('ETenShareAde', [q2[k][E]['ade1']['fraction_reproduced'] for k in A], pct)
    rng('ETenShareFlip', [q2[k][E]['flip']['fraction_reproduced'] for k in A], pct)
    rng('ETenTauLat', [q1[k][E]['spread_lat']['tau_eff'] for k in A], num)
    rng('ETenTauEnergy', [q1[k][E]['energy']['tau_eff'] for k in A], num)
    rng('MarginOverEffect', [q2[k][E][m]['margin_over_effect'] for k in A for m in ('ade1', 'flip')], pct)
    one = lambda x: num(100 * x, 1)
    rng('HeunFar', [q5[k]['vs_reference'][H]['per_noise_frac_above_1m'] for k in A], one)
    rng('HeunNearBoundary', [q5[k]['vs_reference'][H]['flips_ref_margin_below_0.25'] for k in A], pct)
    rng('ETenNearBoundary', [q5[k]['vs_reference'][E]['flips_ref_margin_below_0.25'] for k in A], pct)
    rng('HeunLatFlip', [q5[k]['vs_reference'][H]['lat_flip_rate'] for k in A], one)
    rng('HeunLongFlip', [q5[k]['vs_reference'][H]['long_flip_rate'] for k in A], one)
    rng('HeunGapRatio', [q5[k]['convergence']['heun5_vs_heun32_median_m'] / q5[k]['convergence']['heun32_vs_heun64_median_m'] for k in A], lambda x: num(x, 0))
    rng('EOneLatShare', [q7[k]['spread_lat'] for k in A], pct)
    rng('EOneLongShare', [q7[k]['spread_long'] for k in A], pct)
    (OUT / 'numbers_robustness.tex').write_text('\n'.join(L) + '\n')
    tab = ['% Generated by paper/tables/make_robustness.py (EXPLORATORY / POST HOC); do not edit by hand.',
           '\\begin{table*}[t]', '  \\caption{\\textbf{Robustness of FROST (post hoc, exploratory).} 400 held-out clips; 2000 clip resamples as in the main analysis. '
           '$\\tau_\\mathrm{eff}$ under five matching statistics: mean pairwise spread (paper), longitudinal-only and lateral-only spread, median pairwise distance, '
           'and the $\\tau$ minimizing the energy distance between plan sets; $^\\ast$: the joint ADE$_1$/flip TOST verdict differs from the paper\'s. '
           'Cooling share: $(\\text{effect}-\\text{residual})/\\text{effect}$ in \\%, 95\\% interval (--: effect interval includes zero or share undefined). Energy at 1.00: minimum at the grid edge. '
           '$k{=}3$: range of $\\tau_\\mathrm{eff}$ over the 20 three-noise subsets. Thresholds: flip-verdict agreement over 12 perturbations of the class thresholds (all $\\times0.8$--$1.2$, each $\\times0.8/1.2$). The six initial noises are the same vectors for every clip (one seeded draw per seed), so sampler and reference are paired by noise and all intervals are conditional on these six noises.}',
           '  \\label{tab:robustness}', '  \\centering\\footnotesize\\setlength{\\tabcolsep}{3pt}', '  \\begin{tabular}{@{}llccccccccc@{}}', '    \\toprule',
           '    & & \\multicolumn{5}{c}{$\\tau_\\mathrm{eff}$ by matching statistic} & \\multicolumn{2}{c}{Cooling share (\\%)} & & \\\\',
           '    \\cmidrule(lr){3-7}\\cmidrule(lr){8-9}',
           '    Model & Sampler & Mean & Long & Lat & Median & Energy & ADE$_1$ & Flips & $k{=}3$ & Thresh. \\\\', '    \\midrule',
           *['    ' + x for x in rows], '    \\bottomrule', '  \\end{tabular}', '\\end{table*}']
    (OUT / 'tab_robustness.tex').write_text('\n'.join(tab) + '\n')
    print('\n'.join(L)); print('\n'.join(tab))


if __name__ == '__main__': main()
